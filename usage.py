    # Keywords that map a filename to a Cross-Case subcategory.
    _CROSS_SUBCAT_KEYWORDS = {
        "Velocity":             ["U_Normalized", "V_Centerline", "W_Centerline", "Vmag",
                                 "over_Umax"],   # covers NearNozzle/MidField/NearPlate U/V/W/Vmag
        "Turbulence Intensity": ["I_u", "I_v", "I_w", "I_uvw"],
        "Plane Jet Decay":      ["Plane_Jet_Decay"],
        "Frequency":            ["Freq", "Dominant", "PSD", "Strouhal", "Centerline_St", "Cascade"],
    }

    def _cross_subcat_for_file(self, filename):
        """Return the Cross-Case subcategory name for *filename* (basename)."""
        for subcat, keywords in self._CROSS_SUBCAT_KEYWORDS.items():
            for kw in keywords:
                if kw in filename:
                    return subcat
        return "Other"

    def _filter_by_cross_subcat(self, files, subcat):
        """Return the subset of *files* that belong to *subcat* ('All' returns all)."""
        if subcat == "All":
            return files
        return [f for f in files if self._cross_subcat_for_file(os.path.basename(f)) == subcat]

    def _filter_by_cross_slice(self, files, slice_sel):
        """Filter cross-case superposed figures by profile slice.

        Station figures carry 'NearNozzle' / 'MidField' / 'NearPlate' in their
        filename (X/B sweep at the first / middle / last station); everything else
        in the Cross-Case set is a centerline / global summary. ('All' returns all.)"""
        if slice_sel == "All":
            return files
        _markers = {"Near-nozzle": "NearNozzle", "Mid-field": "MidField",
                    "Near-plate": "NearPlate"}
        out = []
        for f in files:
            base = os.path.basename(f)
            is_station = any(m in base for m in _markers.values())
            if slice_sel in _markers:
                if _markers[slice_sel] in base:
                    out.append(f)
            elif slice_sel == "Centerline" and not is_station:
                out.append(f)
        return out

