    # ==========================================
    # THERMAL-HYDRAULIC PEC (pumping penalty)
    # ==========================================
    def run_pec_tool(self):
        """Compute the Webb PEC (Nu/Nu0)/(f/f0)^(1/3) from the pumping-penalty
        workbook + the thermal summary, show the per-Re table, and refresh the
        gallery (the PEC_vs_Re figure is written into summary/)."""
        def _run():
            try:
                _curves, pec = pec_processor.run()
                cols = ['Setpoint_Pa', 'Re', 'Nu_over_Nu0', 'f_over_f0',
                        'ff0_pow_1_3', 'PEC', 'u_PEC_pct']
                hdr = f"{'Pa':>3} {'Re':>8} {'Nu/Nu0':>7} {'f/f0':>6} {'(f/f0)^1/3':>11} {'PEC':>6} {'u_PEC%':>7}"
                lines = [hdr, "-" * len(hdr)]
                for _, r in pec[cols].iterrows():
                    lines.append(f"{int(r['Setpoint_Pa']):>3} {r['Re']:>8.0f} "
                                 f"{r['Nu_over_Nu0']:>7.3f} {r['f_over_f0']:>6.2f} "
                                 f"{r['ff0_pow_1_3']:>11.3f} {r['PEC']:>6.3f} "
                                 f"{r['u_PEC_pct']:>6.1f}%")
                lo, hi = pec['PEC'].min(), pec['PEC'].max()
                lines += ["", f"PEC range: {lo:.3f}-{hi:.3f}  (>1 = net benefit at constant pumping power)",
                          "Figure 'PEC_vs_Re' written to summary/ and pumping_penalty/."]
                self.root.after(0, lambda t="\n".join(lines): self._show_pec_window(t))
                self.root.after(0, self.refresh_gallery_categories)
            except Exception as e:
                self.root.after(0, lambda err=str(e): messagebox.showerror(
                    "PEC failed", f"Could not compute PEC:\n{err}"))

        threading.Thread(target=_run, daemon=True).start()

