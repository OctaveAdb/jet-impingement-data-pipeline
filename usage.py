# Purpose:
#   Serves as the central graphical hub for the entire jet impingement
#   analysis pipeline. The interface presents a scrollable sidebar of tools
#   grouped into sections — a prominent global-pipeline launcher, a
#   collapsible Single-Case Pipeline section, and a Cross-Case Analysis
#   section — each launching the corresponding script in a new Tkinter window
#   with the global workspace folder automatically propagated. The main area
#   hosts an image gallery that discovers and displays all PNG figures
#   generated by the pipeline, organised by category (experiment subfolder,
#   thermal summaries, or cross-case summaries). The automated pipeline is
#   launched as a subprocess (pipeline.py) with parameters serialised to a
#   temporary JSON file. The Cross-Case Analysis section invokes the
#   superposition module to aggregate results across all experiment subfolders
#   and refresh the gallery. This script is the recommended entry point for
#   interactive use of the pipeline.
#
# Inputs:
#   - Global workspace folder selected by the user via the Browse button;
#     the folder must contain either an experiments/ subfolder with case
#     subfolders or be a direct case folder depending on the tool selected
#
# Outputs:
#   - No files are written by this script directly; it delegates all
#     computation and file I/O to the constituent processor and visualiser
#     scripts it launches
#
# Dependencies:
#   - All 12 processor and visualiser scripts (imported at startup):
#     thermal_processor, thermal_visualizer, Re_Ve_processor,
#     Re_comparison_processor, read_th_file_processor, mean_processor,
#     maps_2D_visualizer, graphs_1D_visualizer, frequency_processor,
#     frequency_visualizer, superposition
#   - pipeline.py (launched as a subprocess for the automated pipeline)
#
# Usage:
#   - python usage.py  (opens the Jet Impingement Analysis Hub GUI)
#   - This is the primary entry point for interactive analysis sessions
# =============================================================================

