    def launch_tool(self, app_class, name):
        if not MODULES_LOADED or app_class.__name__ not in globals():
            messagebox.showerror("Dependency Error", f"Module missing: {name}")
            return
        try:
            new_window = tk.Toplevel(self.root)
            app_class(new_window, default_folder=self.get_target_folder())
        except Exception as e:
            messagebox.showerror("Execution Error", f"Error:\n{e}")

