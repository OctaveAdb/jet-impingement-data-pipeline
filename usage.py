    def run_vertical_slice_profiles(self):
        folder = self.get_target_folder()
        if not folder or not os.path.exists(folder):
            messagebox.showwarning("Input Needed", "Please select a valid case folder first.")
            return
        def _run():
            try:
                save_vertical_slice_profiles(folder)
                self.root.after(0, self.refresh_gallery_categories)
                self.root.after(0, lambda: messagebox.showinfo(
                    "Done", "Vertical slice profiles saved to 2D_Profiles_Results/PNG/"))
            except Exception as e:
                self.root.after(0, lambda: messagebox.showerror("Error", str(e)))
        threading.Thread(target=_run, daemon=True).start()

