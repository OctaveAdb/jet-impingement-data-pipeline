    # ==========================================
    # FULL ANALYSIS PIPELINE — ALL CASES
    # ==========================================
    def run_full_analysis_pipeline(self):
        """Run the full pipeline for ALL cases in experiments/, then run cross-case analysis."""
        parent_dir = self.global_folder.get()
        if not parent_dir or not os.path.exists(parent_dir):
            messagebox.showwarning("Input Needed", "Please select a valid Global Workspace first.")
            return

        experiments_dir = os.path.join(parent_dir, "experiments")
        if not os.path.isdir(experiments_dir):
            messagebox.showerror("Error", f"No experiments/ folder found in:\n{parent_dir}")
            return

        # First: process any new data in new_data/
        new_data_dir = os.path.join(parent_dir, "new_data")
        if os.path.isdir(new_data_dir):
            new_cases = [f.path for f in os.scandir(new_data_dir) if f.is_dir()]
            if new_cases:
                try:
                    from data_intake import register_case
                    for case_path in new_cases:
                        try:
                            success, msg = register_case(
                                os.path.basename(case_path), new_data_dir, experiments_dir,
                                os.path.join(parent_dir, 'config', 'config_cases.xlsx')
                            )
                            self.log_msg(f"Intake: {msg}")
                        except Exception as e:
                            self.log_msg(f"Intake error: {e}")
                except ImportError as e:
                    self.log_msg(f"data_intake not available: {e}")

        # Then: run single-case pipeline for each case
        cases = sorted([f.path for f in os.scandir(experiments_dir) if f.is_dir()])
        if not cases:
            messagebox.showinfo("Info", "No cases found in experiments/")
            return

        pipeline_path = os.path.join(_script_dir, 'scripts', 'pipeline', 'pipeline.py')

        # Build config from config CSV files — no dependency on GUI fields
        def _g(key, fallback):
            try: return float(_cfg_geom[key]) if _cfg_geom is not None else fallback
            except Exception: return fallback
        config_data = {
            'B_mm':   _g('nozzle_height_B', 30.0),
            'step_x': _g('grid_step_x', 5.0),
            'step_y': _g('grid_step_y', 1.5875),
            'x_start': _g('x_start_offset', 38.0),
            'y_start': 0.0, 'az': 0.0, 'el': 0.0, 'roll': 0.0,
            'd_cyl': _g('cylinder_diameter_D2', 12.0),
            'w_noz': _g('nozzle_width_cyl', 156.0),
            'd1':    _g('tunnel_diameter_D1', 200.0),
            'dp': 0.0,
        }
        config_file_path = os.path.join(_script_dir, 'config', '_pipeline_run_config.json')
        with open(config_file_path, 'w') as _f:
            json.dump(config_data, _f)

        def _run_sequentially():
            for i, case_path in enumerate(cases, 1):
                case_name = os.path.basename(case_path)
                self.log_msg(f"[{i}/{len(cases)}] Starting pipeline for: {case_name}")
                p = subprocess.Popen(
                    [sys.executable, pipeline_path, "--folder", case_path, "--config", config_file_path]
                )
                p.wait()  # wait for this case to finish before starting the next
                self.log_msg(f"[{i}/{len(cases)}] Finished: {case_name}")

            # All cases done — run cross-case superposition
            try:
                generate_superposition(parent_dir)
                self.root.after(0, lambda: messagebox.showinfo(
                    "Done",
                    f"Full analysis pipeline complete!\n{len(cases)} case(s) processed sequentially.\nSuperposition generated."
                ))
                self.root.after(0, self.refresh_gallery_categories)
            except Exception as e:
                self.root.after(0, lambda: messagebox.showerror("Error", f"Superposition failed:\n{e}"))

        threading.Thread(target=_run_sequentially, daemon=True).start()
        messagebox.showinfo(
            "Running",
            f"Full pipeline started — processing {len(cases)} case(s) one at a time.\n"
            "Progress is printed to the console. The GUI stays responsive."
        )

    # ==========================================
    # THERMAL ANALYSIS PIPELINE
    # ==========================================
    def run_thermal_pipeline(self):
        """Single-button thermal analysis: compute → save figures → refresh gallery."""
        folder = self.global_folder.get()
        if not folder or not os.path.exists(folder):
            messagebox.showwarning("Input Needed", "Please select a valid Global Workspace first.")
            return

        def _run():
            # Step 1 — run thermal_processor headlessly in a withdrawn Tk window
            _root = tk.Tk()
            _root.withdraw()
            try:
                app = ThermalProcessorApp(_root, default_folder=folder)
                app.run_master_pipeline(folder)   # synchronous call — we are already in a background thread
            except Exception as e:
                self.root.after(0, lambda err=str(e): messagebox.showerror(
                    "Thermal Processing Error", f"Processing failed:\n{err}"
                ))
                return
            finally:
                try: _root.destroy()
                except Exception: pass

            # Step 2 — save all figures headlessly
            _, msg = save_all_thermal_figures(folder)

            # Step 3 — refresh gallery and notify
            self.root.after(0, self.refresh_gallery_categories)
            self.root.after(0, lambda m=msg: messagebox.showinfo(
                "Thermal Analysis Complete",
                f"Processing and figures complete.\n{m}"
            ))

        threading.Thread(target=_run, daemon=True).start()
        messagebox.showinfo(
            "Thermal Analysis Running",
            "Thermal processing started in background.\n"
            "The gallery will update automatically when done."
        )

