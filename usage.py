    def select_global_folder(self):
        folder = filedialog.askdirectory(title="Select Global Workspace Folder")
        if folder:
            self.global_folder.set(folder)
            self._populate_local_folders()
            self.refresh_gallery_categories()

    def _list_case_folders(self):
        """Return sorted case-folder names inside the global workspace.

        Cases live under experiments/ in the current layout; the old flat
        layout keeps them at the workspace root. Non-case helper folders are
        excluded in both cases."""
        root = self.global_folder.get()
        if not root or not os.path.isdir(root):
            return []
        _exclude = {'summary', 'thermal', 'experiments', 'scripts',
                    'config', 'new_data', '__pycache__'}
        exp = os.path.join(root, "experiments")
        scan_dir = exp if os.path.isdir(exp) else root
        try:
            return sorted(
                f.name for f in os.scandir(scan_dir)
                if f.is_dir() and f.name.lower() not in _exclude
            )
        except Exception:
            return []

    def _populate_local_folders(self):
        """Refresh the local-folder dropdown from the current global workspace."""
        cases = self._list_case_folders()
        values = [self.GLOBAL_OPTION] + cases
        if hasattr(self, 'combo_local'):
            self.combo_local['values'] = values
        # Reset selection to the global sentinel if the previous pick vanished.
        if self.local_folder.get() not in values:
            self.local_folder.set(self.GLOBAL_OPTION)

    def get_target_folder(self):
        """Folder for SINGLE-CASE tools.

        Returns the selected local case folder, or the global workspace when
        the user has chosen to stay in the global folder (the GLOBAL_OPTION
        sentinel)."""
        root = self.global_folder.get()
        if not root:
            return None
        sel = self.local_folder.get()
        if sel and sel != self.GLOBAL_OPTION:
            exp = os.path.join(root, "experiments")
            base = exp if os.path.isdir(exp) else root
            candidate = os.path.join(base, sel)
            if os.path.isdir(candidate):
                return candidate
        return root

