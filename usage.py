    _CASE_TYPE_KEYWORDS = {
        "Velocity":             ["U_over", "V_over", "W_over", "Vmag", "U_max", "Velocity"],
        "Turbulence Intensity": ["I_u", "I_v", "I_w", "I_uvw", "Turbulence"],
        "Frequency":            ["PSD", "FFT", "Freq", "Strouhal", "Centerline_St",
                                 "Coherence", "Cascade"],
        "2D Profiles":          ["Transverse", "Butterfly", "VSlice"],
    }

    def _case_type_for_file(self, filename):
        """Return the single-case Type for *filename*."""
        for type_name, keywords in self._CASE_TYPE_KEYWORDS.items():
            for kw in keywords:
                if kw in filename:
                    return type_name
        return "Miscellaneous"

    def _filter_by_case_type(self, files, type_sel):
        """Filter *files* by the selected Type ('All' returns all)."""
        if type_sel == "All":
            return files
        return [f for f in files if self._case_type_for_file(os.path.basename(f)) == type_sel]

    def _filter_by_case_slice(self, files, slice_sel):
        """Filter *files* by slice orientation ('All', 'Horizontal', 'Vertical')."""
        if slice_sel == "All":
            return files
        result = []
        for f in files:
            bn = os.path.basename(f)
            if slice_sel == "Horizontal" and "_Y_" in bn:
                result.append(f)
            elif slice_sel == "Vertical" and ("_X_" in bn or "XB" in bn):
                result.append(f)
        return result

