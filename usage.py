    def _get_relevant_pngs(self, folder):
        """Helper logic to detect parent folders and specific subfolders like thermal."""
        summary_dir = os.path.join(folder, "summary")
        temp_dir = os.path.join(folder, "thermal")
        pump_dir = os.path.join(folder, "pumping_penalty")
        experiments_dir = os.path.join(folder, "experiments")
        is_parent = False

        try:
            # Check experiments/ subfolder for experiment case folders
            if os.path.isdir(experiments_dir):
                for item in os.listdir(experiments_dir):
                    full_path = os.path.join(experiments_dir, item)
                    if os.path.isdir(full_path):
                        if os.path.exists(os.path.join(full_path, "Processed_CSVs")) or \
                           os.path.exists(os.path.join(full_path, "2D_Profiles_Results")):
                            is_parent = True
                            break
            # Fallback: check root-level folders (old structure)
            if not is_parent:
                for item in os.listdir(folder):
                    if item in ["summary", "thermal", "experiments", "scripts", "__pycache__"]:
                        continue
                    full_path = os.path.join(folder, item)
                    if os.path.isdir(full_path):
                        if os.path.exists(os.path.join(full_path, "Processed_CSVs")) or \
                           os.path.exists(os.path.join(full_path, "2D_Profiles_Results")):
                            is_parent = True
                            break
        except Exception:
            pass

        files = []
        if is_parent:
            # Grab Aerodynamic Summaries
            if os.path.exists(summary_dir):
                files.extend(glob.glob(os.path.join(summary_dir, "**", "*.png"), recursive=True))
            # Grab Thermal Summaries from thermal folder
            if os.path.exists(temp_dir):
                files.extend(glob.glob(os.path.join(temp_dir, "**", "*.png"), recursive=True))
            # Grab Pumping-Penalty / PEC figures
            if os.path.exists(pump_dir):
                files.extend(glob.glob(os.path.join(pump_dir, "*.png")))
        else:
            files = glob.glob(os.path.join(folder, "**", "*.png"), recursive=True)

        return [f for f in files if "__pycache__" not in f]

    def _get_category_for_file(self, filepath):
        """Intelligently assigns a clean category name based on the file's path."""
        parts = filepath.split(os.sep)
        if "pumping_penalty" in parts:
            return "Pumping Penalty / PEC"
        if "thermal" in parts:
            return "Thermal Summaries"
        elif "summary" in parts:
            return "Cross-Case Summaries"
        else:
            parent_dir = os.path.basename(os.path.dirname(filepath))
            grandparent_dir = os.path.basename(os.path.dirname(os.path.dirname(filepath)))
            return f"{grandparent_dir} / {parent_dir}" if parent_dir == "PNG" else parent_dir

    def refresh_gallery_categories(self):
        folder = self.get_view_folder()
        if not folder or not os.path.exists(folder):
            return

        png_files = self._get_relevant_pngs(folder)

        categories = set()
        for f in png_files:
            categories.add(self._get_category_for_file(f))

        cats = sorted(list(categories))
        if cats:
            self.combo_category['values'] = cats
            self.combo_category.current(0)
            self._reset_subfilters()
            self._update_filter_visibility()
            self.load_gallery_images()
        else:
            self.combo_category['values'] = ["No images found"]
            self.combo_category.current(0)
            self._update_filter_visibility()
            self.combo_image['values'] = [""]
            self.combo_image.set("")
            self.gallery_images = []
            self.display_selected_image()

    def _reset_subfilters(self):
        """Reset all sub-filter combos to 'All' and clear dynamic value lists."""
        self.gallery_cross_subcat.set("All")
        self.gallery_cross_slice.set("All")
        self.gallery_case_type.set("All")
        self.gallery_case_slice.set("All")
        # Reset option lists so stale values from the previous category are not
        # visible in the dropdown while the new category's images are loading.
        self.combo_case_type['values'] = ["All"]
        self.combo_case_slice['values'] = ["All"]

