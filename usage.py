    def _present_types(self, files):
        """Return sorted list of Type labels actually represented in *files*."""
        seen = set()
        for f in files:
            seen.add(self._case_type_for_file(os.path.basename(f)))
        return sorted(seen)

    def _present_slices(self, files):
        """Return sorted list of Slice display labels actually represented in *files*.

        Only the two recognised orientations are checked; files that match
        neither are silently omitted (they will still appear under 'All').
        """
        seen = set()
        for f in files:
            bn = os.path.basename(f)
            if "_Y_" in bn:
                seen.add("Horizontal (Y/B=0)")
            if "_X_" in bn or "XB" in bn:
                seen.add("Vertical (X/B=const)")
        return sorted(seen)

    def _on_subfilter_changed(self, event=None):
        """Called when any sub-filter combobox selection changes."""
        self._apply_gallery_filters()

    def load_gallery_images(self, event=None):
        """Load images for the selected category, then reset sub-filters and apply them."""
        folder = self.get_view_folder()
        target_cat = self.combo_category.get()
        if not folder or target_cat == "No images found":
            return

        # Reset sub-filters and update which rows are visible whenever category changes
        self._reset_subfilters()
        self._update_filter_visibility()

        all_pngs = self._get_relevant_pngs(folder)
        # Build full list for this category (unfiltered)
        self._gallery_images_unfiltered = [
            f for f in all_pngs if self._get_category_for_file(f) == target_cat
        ]
        self._gallery_images_unfiltered.sort()

        self._apply_gallery_filters()

    def _apply_gallery_filters(self, event=None):
        """Re-filter _gallery_images_unfiltered using active sub-filter selections.

        For single-case categories this also:
          - Repopulates the Type combobox with only the types present in the
            current image set; resets to 'All' if the prior selection vanished.
          - After applying the Type filter, repopulates the Slice combobox with
            only the slice orientations present among the type-filtered files;
            resets to 'All' if the prior selection vanished.
          - Hides the Slice row entirely when fewer than two slice orientations
            exist (it would add no useful discrimination).
        """
        if not hasattr(self, '_gallery_images_unfiltered'):
            return

        files = list(self._gallery_images_unfiltered)
        cat = self.combo_category.get()

        if self._is_cross_case_category(cat):
            files = self._filter_by_cross_subcat(files, self.gallery_cross_subcat.get())
            files = self._filter_by_cross_slice(files, self.gallery_cross_slice.get())

        elif self._is_single_case_category(cat):
            # --- Step 1: repopulate Type combo from the full unfiltered set ---
            present_types = self._present_types(files)
            type_options = ["All"] + present_types
            self.combo_case_type['values'] = type_options
            if self.gallery_case_type.get() not in type_options:
                self.gallery_case_type.set("All")

            # --- Step 2: apply Type filter ---
            files = self._filter_by_case_type(files, self.gallery_case_type.get())

            # --- Step 3: repopulate Slice combo from the type-filtered set ---
            present_slices = self._present_slices(files)
            slice_options = ["All"] + present_slices
            self.combo_case_slice['values'] = slice_options
            if self.gallery_case_slice.get() not in slice_options:
                self.gallery_case_slice.set("All")

            # Hide Slice row when there is at most one distinct orientation
            # (nothing useful to filter on); show it otherwise.
            if len(present_slices) < 2:
                self.row_case_slice.pack_forget()
            else:
                # Re-pack only if the type row is already visible (safety guard)
                if self.row_case_type.winfo_ismapped():
                    self.row_case_slice.pack(fill="x", pady=2)

            # --- Step 4: apply Slice filter ---
            slice_val = self.gallery_case_slice.get()
            if "Horizontal" in slice_val:
                slice_key = "Horizontal"
            elif "Vertical" in slice_val:
                slice_key = "Vertical"
            else:
                slice_key = "All"
            files = self._filter_by_case_slice(files, slice_key)

        self.gallery_images = files
        pretty_names = [self.get_pretty_name(os.path.basename(f)) for f in self.gallery_images]
        self.combo_image['values'] = pretty_names

        if pretty_names:
            self.combo_image.current(0)
            self.display_selected_image()
        else:
            self.combo_image.set("")
            self.lbl_image.config(image='', text="No images match the selected filters.")

